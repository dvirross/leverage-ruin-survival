def leverage_experiment(df: pd.DataFrame, sample: str):
    r, rf = df["MKT"].to_numpy(), df["RF"].to_numpy()
    n = len(r)
    rows = []
    for h in HORIZONS:
        nd = h * TRADING_DAYS
        starts = window_starts(n, nd, STEP)
        for sp in SPREADS:
            specs = [("daily", L, None, np.nan) for L in L_DAILY] + \
                    [(f"loan_{a}", L, a, mt) for mt in MAINTS for a in ("close", "restore") for L in L_LOAN]
            for kind, L, act, mt in specs:
                if act is None:
                    o = sweep_daily(r, rf, starts, nd, L, sp)
                    wiped = o["final"] <= 0
                    pmc = np.nan
                else:
                    o = sweep_margin(r, rf, starts, nd, L, mt, sp, act)
                    wiped = o["wiped"]
                    pmc = float((o["ncalls"] > 0).mean())
                g = annualized_growth(o["final"], nd)
                rows.append({"sample": sample, "kind": kind, "L": L, "maintenance": mt, "spread_annual": sp, "horizon_years": h,
                             "n_windows": len(starts),
                             "mean_arith_annual_return": float(((o["final"] - 1.0) / h).mean()),
                             "median_growth": float(np.median(g)), "p10_growth": float(np.percentile(g, 10)),
                             "p_wipeout": float(wiped.mean()), "p_margin_call": pmc,
                             "p_fall_50pct": float((o["min"] <= 0.5).mean()),
                             "p_below_start": float((o["final"] < 1.0).mean())})
    win = pd.DataFrame(rows)
    # full sample, one path
    frows = []
    for sp in SPREADS:
        for L in L_DAILY:
            path = daily_rebalanced(r, rf, L, sp)
            s_ = sp / TRADING_DAYS if L > 1 else 0.0
            eq = L * r - (L - 1.0) * (rf + s_)
            frows.append({"sample": sample, "kind": "daily", "L": L, "maintenance": np.nan, "spread_annual": sp,
                          "years": n / TRADING_DAYS, "annualized_growth": growth_rate(path),
                          "mean_daily_equity_return_x252": float(eq.mean() * TRADING_DAYS),
                          "final_equity": float(path[-1]), "max_drawdown": max_drawdown(path),
                          "margin_calls": np.nan, "first_call_date": "", "closed_date": ""})
        for mt, act, L in [(mt, a, L) for mt in MAINTS for a in ("close", "restore") for L in L_LOAN]:
            if True:
                res = margin_loan(r, rf, L, mt, sp, act)
                fin = float(res.equity[-1])
                yrs = n / TRADING_DAYS
                frows.append({"sample": sample, "kind": f"loan_{act}", "L": L, "maintenance": mt, "spread_annual": sp, "years": yrs,
                              "annualized_growth": (fin ** (1 / yrs) - 1) if fin > 0 else -1.0,
                              "mean_daily_equity_return_x252": np.nan, "final_equity": fin,
                              "max_drawdown": max_drawdown(np.maximum(res.equity, 1e-12)) if fin > 0 else -1.0,
                              "margin_calls": len(res.calls),
                              "first_call_date": str(df.index[res.calls[0] - 1].date()) if res.calls else "",
                              "closed_date": str(df.index[res.closed_at - 1].date()) if res.closed_at else ""})
    return win, pd.DataFrame(frows)


def growth_curve(r, rf, grid, sp):
    """Annualised growth (effective) of daily rebalanced leverage for each L in grid; -1 if any day <= -100%."""
    out = np.empty(len(grid))
    for i, L in enumerate(grid):
        s_ = sp / TRADING_DAYS if L > 1 else 0.0
        eq = L * r - (L - 1.0) * (rf + s_)
        out[i] = -1.0 if (eq <= -1).any() else np.expm1(np.log1p(eq).mean() * TRADING_DAYS)
    return out


